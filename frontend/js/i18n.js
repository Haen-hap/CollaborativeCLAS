function getSavedLanguage() {
  try { return localStorage.getItem(LANGUAGE_KEY) === "en" ? "en" : "es"; }
  catch (error) { return "es"; }
}
let currentLanguage = getSavedLanguage();
function t(key, values = {}) {
  const value = MESSAGES[currentLanguage][key] ?? MESSAGES.es[key] ?? key;
  return value.replace(/\{(\w+)\}/g, (match, name) => values[name] == null ? match : String(values[name]));
}
function tContent(spanishValue) {
  const key = ASSESSMENT_COPY_KEYS[spanishValue];
  return key ? (CONTENT_MESSAGES[currentLanguage][key] ?? CONTENT_MESSAGES.es[key] ?? spanishValue) : spanishValue;
}
function setLanguage(language) {
  currentLanguage = language === "en" ? "en" : "es";
  try { localStorage.setItem(LANGUAGE_KEY, currentLanguage); } catch (error) {}
  document.documentElement.lang = currentLanguage;
  document.title = t("app.title");
  return currentLanguage;
}
